// `english` in `language` (Wii U code), or `english`
inline std::string tr(const std::string& english, uint32_t language) {
    if (language < 2 || language > 5) return english;
    const auto& t = table();
    const auto it = t.find(english);
    if (it == t.end()) return english;
    const Line& l = it->second;
    const char* s = language == 2 ? l.fr : language == 3 ? l.de : language == 4 ? l.it : l.es;
    return s ? s : english;
}

