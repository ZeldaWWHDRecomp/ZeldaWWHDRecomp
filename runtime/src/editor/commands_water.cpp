// ---------------------------------------------------------------- planning one body
// Everything a body of water needs, worked out from world parameters: its place, its two models (bytes and
// manifest entries), its actor, and what is wrong with it. `replacing`: the actor being rebuilt (edit_water).
struct WaterPlan {
    std::string kind, id;
    water::Params params;
    XZ origin;
    int origin_y = 0;
    std::string stage;
    int room = -1;
    water::Built built;
    std::vector<water::Problem> problems;
    Value actor, main_entry, surface_entry;
};

static bool plan_water(Host* host, const Value& manifest, const std::string& kind, const Value& p, const std::string& replacing, WaterPlan& out, std::string& why) {
    out = WaterPlan();
    out.kind = kind;
    const Value& pts = p.get("points");
    if (pts.type != Value::Array || pts.array.empty()) return why = "\"points\" is a list of {x, z} places in the world", false;
    // the place: the points' middle (whole units)
    double sx = 0, sz = 0, top_y = -1e9;
    bool have_y = false;
    for (const auto& v : pts.array) {
        double x, z;
        if (v.type == Value::Object) x = v.get("x").number, z = v.get("z").number;
        else if (v.type == Value::Array && v.array.size() >= 2) x = v.array[0].number, z = v.array[1].number;
        else return why = "each point is {x, z} (or {x, y, z}) in world units", false;
        if (!std::isfinite(x) || !std::isfinite(z)) return why = "each point is {x, z} (or {x, y, z}) in world units", false;
        sx += x, sz += z;
        double y;
        if (point_y(v, y)) top_y = std::max(top_y, y), have_y = true;
    }
    out.origin = {int(std::lround(sx / double(pts.array.size()))), int(std::lround(sz / double(pts.array.size())))};
    if (kind == "pond" && p.get("level").type == Value::Number) out.origin_y = int(std::lround(p.get("level").number));
    if (kind == "waterfall" && p.get("top").type == Value::Number) out.origin_y = int(std::lround(p.get("top").number));
    // the stage and room: on the sea (a water surface is island presentation, sea only), the square under it
    const Place link = host ? host->link() : Place();
    out.stage = p.get("stage").type == Value::String ? p.get("stage").text : link.valid ? link.stage : "sea";
    if (out.stage != "sea") return why = "bodies of water are made on the sea's islands (stage \"sea\"); this is " + out.stage, false;
    out.room = p.get("room").type == Value::Number ? int(p.get("room").number) : sea_room(float(out.origin.x), float(out.origin.z));
    if (out.room < 1 || out.room > 49) return why = "the water is not on the Great Sea's chart", false;
    if (!water::parse(kind, p, out.origin, out.origin_y, out.params, why)) return false;
    Value q = p;
    // a waterfall falls to the lower side of its edge (unless "side" says which)
    if (kind == "waterfall" && p.get("side").type == Value::Null && out.params.points.size() == 2 && host) {
        const double above = (p.get("top").type == Value::Number ? std::max(double(out.origin_y), have_y ? top_y : -1e9) : have_y ? top_y : 19400.0) + 600;
        std::vector<WorldPoint> feet;
        for (int side : {1, -1}) {
            water::Params t = out.params;
            t.side = side;
            const XZ foot = water::ground_places(t, out.origin).back();
            feet.push_back({float(foot.x), float(above), float(foot.z)});
        }
        std::vector<float> heights;
        std::vector<bool> found;
        std::string w;
        if (host->grounds(feet, heights, found, w) && found.size() == 2) {
            const int side = !found[1] ? 1 : !found[0] ? -1 : heights[1] < heights[0] ? -1 : 1;
            q["side"] = double(side);
            out.params.side = side;
        }
    }
    // the ground under it: what the parameters kept (an unmoved point) or the game's answer now
    std::vector<water::Sample> kept = out.params.ground;
    out.params.ground.clear();
    const auto places = water::ground_places(out.params, out.origin);
    std::vector<WorldPoint> ask;
    std::vector<size_t> asked;
    // asked from above the highest picked point (or the given level / top), else from high in the sky
    const bool given = (kind == "pond" && p.get("level").type == Value::Number) || (kind == "waterfall" && p.get("top").type == Value::Number);
    const double above = (given && have_y ? std::max(double(out.origin_y), top_y) : given ? double(out.origin_y) : have_y ? top_y : 19400.0) + 600;
    for (size_t i = 0; i < places.size(); i++) {
        const auto found = std::find_if(kept.begin(), kept.end(), [&](const water::Sample& s) { return s.x == places[i].x && s.z == places[i].z; });
        const bool dup = std::any_of(out.params.ground.begin(), out.params.ground.end(), [&](const water::Sample& s) { return s.x == places[i].x && s.z == places[i].z; });
        if (dup) continue;
        if (found != kept.end()) out.params.ground.push_back({found->x, found->z, std::max(0, found->h)});
        else ask.push_back({float(places[i].x), float(above), float(places[i].z)}), asked.push_back(i);
    }
    if (!ask.empty() && host) {
        std::vector<float> heights;
        std::vector<bool> found;
        std::string w;
        if (host->grounds(ask, heights, found, w))
            for (size_t k = 0; k < ask.size(); k++)
                // on the sea, ground under the water's surface is the sea there (a harbour, a channel, the open sea
                // beside an island): its surface (y 0) is where the water and the banks meet it, so a pond's level and
                // banks never reach down to the sea floor
                if (found[k] && std::isfinite(heights[k])) out.params.ground.push_back({places[asked[k]].x, places[asked[k]].z, std::max(0, int(std::lround(heights[k])))});
    }
    auto ground_of = [&](XZ world, int& h) {
        for (const auto& s : out.params.ground)
            if (s.x == world.x && s.z == world.z) return h = s.h, true;
        return false;
    };
    // what the ground decides: a pond's level (its depth above the lowest ground at its shore: the island's ground can't
    // be lowered, so water deep enough to swim in stands on it, its banks a low mound round it), a river's height (its
    // first point), a waterfall's top and foot
    if (kind == "pond" && p.get("level").type != Value::Number) {
        int lowest = INT_MAX;
        for (const auto& q : water::shore_places(out.params, out.origin)) {
            int h;
            if (ground_of(q, h)) lowest = std::min(lowest, h);
        }
        if (lowest == INT_MAX) return why = "say the water's height (\"level\"): there is no ground under the outline to take it from", false;
        out.origin_y = lowest + out.params.depth;
    }
    if (kind == "river") {
        int h;
        if (!places.empty() && ground_of(places.front(), h)) out.origin_y = h;
    }
    if (kind == "waterfall" && out.params.points.size() == 2 && places.size() == 3) {
        int ha, hb, hf;
        const bool a = ground_of(places[0], ha), b = ground_of(places[1], hb), f = ground_of(places[2], hf);
        if (p.get("top").type != Value::Number) {
            if (!a && !b) return why = "say the top edge's height (\"top\"): there is no ground at its points", false;
            out.origin_y = std::max(a ? ha : INT_MIN, b ? hb : INT_MIN);
        }
        if (p.get("bottom").type != Value::Number && !f) return why = "say the height of the ground below (\"bottom\"): there is none in front of the edge", false;
    }
    // the parameters again, relative to the final height; the waterfall's foot from the ground when not given
    if (kind == "waterfall" && p.get("bottom").type != Value::Number) {
        int hf = 0;
        ground_of(places[2], hf);
        q["bottom"] = double(hf);
    }
    if (kind == "waterfall" && p.get("top").type != Value::Number) q["top"] = double(out.origin_y);
    auto ground = out.params.ground;
    if (!water::parse(kind, q, out.origin, out.origin_y, out.params, why)) return false;
    out.params.ground = std::move(ground);
    out.params.room = out.room;
    water::build(out.params, out.origin, out.origin_y, out.built, out.problems);

    // what the package and the game allow
    const Value& models = manifest.get("models");
    size_t count = models.array.size() + 2;
    if (!replacing.empty())
        if (const Value* a = by_id(manifest.get("actors"), replacing))
            for (const char* key : {"model", "shoreline"}) {
                const std::string m = std::string(key) == "model" ? a->get("model").string() : a->get("shoreline").get("model").string();
                const Value* entry = by_id(models, m);
                if (entry && water_model(*entry)) {
                    size_t users = 0;
                    for (const auto& other : manifest.get("actors").array)
                        if (other.get("model").string() == m || other.get("shoreline").get("model").string() == m) users++;
                    if (users <= 1) count--;
                }
            }
    if (count > 8)
        out.problems.push_back({"the mod would have " + std::to_string(count) + " models; a mod has at most 8 and a body of water takes two (remove one, or put it in another mod)", "models"});
    if (replacing.empty()) {
        unsigned in_room = 0;
        for (const auto& a : manifest.get("actors").array)
            if (a.get("stage").string() == out.stage && int(a.get("room").number) == out.room) in_room++;
        if (in_room + 1 > story_notebook::kMaxActorsPerRoom)
            out.problems.push_back({"the room has " + std::to_string(in_room) + " placed actors of this mod already; at most " + std::to_string(story_notebook::kMaxActorsPerRoom), "room"});
    }
    if (host && !has_error(out.problems)) {
        // the known limit: the game looks for water only within the height of the room's own ground
        float low = 0, high = 0;
        std::string w;
        if (host->room_height(out.stage, out.room, low, high, w)) {
            int level = out.origin_y;
            if (kind == "river")
                for (int l : out.built.levels) level = std::max(level, l + out.origin_y);
            if (kind != "waterfall" && level > high)
                out.problems.push_back({"the water's level (" + std::to_string(level) + ") is above the highest ground of this square (" + std::to_string(int(std::floor(high))) +
                                            "): the game won't find this water there (Link would walk on its floor); lower it below the top of the square's island",
                                        "level"});
        }
        // what it would be in the way of: the island's people, routes, doors, chests, events, other mods' objects
        story_notebook::ManifestActor c;
        c.id = replacing.empty() ? "water-check" : replacing;
        c.kind = "mod";
        c.behaviour = "static";
        c.stage = out.stage;
        c.room = unsigned(out.room);
        c.collision_shape = "box";
        const auto& b = out.built;
        c.collision_size = {float(std::max(1, b.max[0] - b.min[0])), float(std::max(1, b.max[1] - b.min[1])), float(std::max(1, b.max[2] - b.min[2]))};
        c.position = {float(out.origin.x + (b.min[0] + b.max[0]) / 2.0), float(out.origin_y + (b.min[1] + b.max[1]) / 2.0), float(out.origin.z + (b.min[2] + b.max[2]) / 2.0)};
        c.shoreline.material = out.built.material;  // a body of water: the island's ground doesn't count
        // its own collision as the game will get it (its open water, floor and banks), where the actor will stand: the
        // world objects it lies on or in (an island ground, a terrace) are in the way only where they rise through its water
        story_world_collision::mesh::Mesh mesh;
        mesh.minimum = {INFINITY, INFINITY, INFINITY}, mesh.maximum = {-INFINITY, -INFINITY, -INFINITY};
        for (const auto& v : b.collision_points) {
            mesh.vertices.push_back({v[0], v[1], v[2]});
            mesh.minimum = {std::min(mesh.minimum.x, v[0]), std::min(mesh.minimum.y, v[1]), std::min(mesh.minimum.z, v[2])};
            mesh.maximum = {std::max(mesh.maximum.x, v[0]), std::max(mesh.maximum.y, v[1]), std::max(mesh.maximum.z, v[2])};
        }
        bool known = !b.collision_faces.empty();
        for (size_t t = 0; t < b.collision_faces.size(); t++) {
            const int surface = static_models::collision_surface(b.collision_materials[t]);
            if (surface < 0) known = false;
            mesh.triangles.push_back({b.collision_faces[t], uint16_t(std::max(surface, 0))});
        }
        Value r;
        bool asked = false;
        if (b.main_triangles && known) {
            auto at = c;
            at.collision_shape.clear();
            at.position = {float(out.origin.x), float(out.origin_y), float(out.origin.z)};
            asked = host->world_object_query_with(text(p, "mod"), at, mesh, r, w);
        } else if (b.main_triangles)
            asked = host->world_object_query(text(p, "mod"), c, false, r, w);
        if (asked)
            for (const auto& x : r.get("conflicts").array) {
                water::Problem e{"in the way: " + conflict_words(x), "points"};
                for (const char* k : {"at", "reach", "path"})
                    if (x.get(k).type != Value::Null) e.where[k] = x.get(k);
                out.problems.push_back(std::move(e));
            }
    }
    return true;
}

// The manifest entries and actor of a plan for `id` (after plan_water succeeded without errors).
static void name_plan(WaterPlan& w, const std::string& id) {
    w.id = id;
    const std::string mid = id + "-m" + digest8(w.built.main), sid = id + "-s" + digest8(w.built.surface);
    w.main_entry = Value();
    w.main_entry["id"] = mid;
    w.main_entry["source"] = "models/water/" + mid + ".glb";
    w.surface_entry = Value();
    w.surface_entry["id"] = sid;
    w.surface_entry["source"] = "models/water/" + sid + ".glb";
    Value a;
    a["id"] = id;
    a["kind"] = "mod";
    a["model"] = mid;
    a["behaviour"] = "static";
    a["stage"] = w.stage;
    a["room"] = double(w.room);
    Value pos;
    pos["x"] = double(w.origin.x), pos["y"] = double(w.origin_y), pos["z"] = double(w.origin.z);
    a["position"] = pos;
    a["collision"]["mesh"] = mid;
    a["shoreline"]["model"] = sid;
    a["shoreline"]["material"] = w.built.material;
    w.actor = a;
}

static Value plan_result(const WaterPlan& w) {
    Value r;
    r["kind"] = w.kind;
    r["problems"].type = Value::Array;
    for (const auto& p : w.problems) r["problems"].array.push_back(problem_value(p));
    r["ok"] = !has_error(w.problems);
    Value at;
    at["x"] = double(w.origin.x), at["y"] = double(w.origin_y), at["z"] = double(w.origin.z);
    r["position"] = at;
    r["stage"] = w.stage;
    r["room"] = double(w.room);
    const auto& b = w.built;
    if (b.main_triangles) {
        r["surface_triangles"] = double(b.surface_triangles);
        r["model_vertices"] = double(b.main_vertices);
        r["model_triangles"] = double(b.main_triangles);
        r["collision_vertices"] = double(b.collision_vertices);
        r["collision_triangles"] = double(b.collision_triangles);
        r["texture_bytes"] = double(b.texture_bytes);
        r["file_bytes"] = double(b.main.size() + b.surface.size());
        r["material"] = b.material;
        Value lo, hi;
        lo["x"] = double(w.origin.x + b.min[0]), lo["y"] = double(w.origin_y + b.min[1]), lo["z"] = double(w.origin.z + b.min[2]);
        hi["x"] = double(w.origin.x + b.max[0]), hi["y"] = double(w.origin_y + b.max[1]), hi["z"] = double(w.origin.z + b.max[2]);
        r["minimum"] = lo, r["maximum"] = hi;
    }
    if (w.kind == "river") {
        r["steps"].type = Value::Array;
        for (const auto& s : b.steps) {
            Value v, l, rr;
            l["x"] = double(s.left.x + w.origin.x), l["z"] = double(s.left.z + w.origin.z);
            rr["x"] = double(s.right.x + w.origin.x), rr["z"] = double(s.right.z + w.origin.z);
            v["left"] = l, v["right"] = rr, v["top"] = double(s.top + w.origin_y), v["bottom"] = double(s.bottom + w.origin_y), v["section"] = double(s.section + 1);
            r["steps"].array.push_back(v);
        }
        r["levels"].type = Value::Array;
        for (int l : b.levels) r["levels"].array.push_back(Value(double(l + w.origin_y)));
    }
    r["ground_samples"] = double(w.params.ground.size());
    return r;
}

// a water body's stored parameters in world form (its actor's place and turn), with its kept ground answers
static bool water_of(const std::string& dir, const Value& manifest, const std::string& id, water::Params& params, Value& world, std::string& why) {
    const Value* a = by_id(manifest.get("actors"), id);
    if (!a) return why = "no placed actor \"" + id + "\"", false;
    const Value* model = by_id(manifest.get("models"), a->get("model").string());
    if (!model || !water_model(*model)) return why = "\"" + id + "\" is not a body of water made with the water tool", false;
    if (dir.empty()) return why = "the mod has no package folder", false;
    std::ifstream f(fs::u8path(dir) / fs::u8path(model->get("source").string()), std::ios::binary);
    const std::vector<uint8_t> bytes((std::istreambuf_iterator<char>(f)), {});
    if (!water::params_from_glb(bytes, params, why)) return why = "\"" + id + "\": " + why, false;
    const Value& pos = a->get("position");
    const XZ origin{int(std::lround(pos.get("x").number)), int(std::lround(pos.get("z").number))};
    const int origin_y = int(std::lround(pos.get("y").number));
    for (const char* k : {"x", "z"})
        if (a->get("scale").type == Value::Object && a->get("scale").get(k).number != 1) return why = "\"" + id + "\" is scaled: set its scale back to 1 to edit it as water", false;
    // its turn (degrees about the vertical axis), baked into the points
    const double yaw = a->get("rotation").get("y").number * 3.14159265358979323846 / 180;
    water::Params turned = params;
    if (yaw != 0)
        for (auto& q : turned.points) {
            const double c = std::cos(yaw), s = std::sin(yaw);
            const double x = c * q.x + s * q.z, z = -s * q.x + c * q.z;
            q = {int(std::lround(x)), int(std::lround(z))};
        }
    world = water::to_value(turned, origin, origin_y);
    world["ground"].type = Value::Array;
    for (const auto& s : params.ground) {
        Value g;
        g.type = Value::Array;
        g.array = {Value(double(s.x)), Value(double(s.z)), Value(double(s.h))};
        world["ground"].array.push_back(g);
    }
    world["stage"] = a->get("stage");
    world["room"] = a->get("room");
    return true;
}

// ---------------------------------------------------------------- session: the water commands
Value Session::dispatch_water(const std::string& command, const Value& p, std::string& why, bool& ok, bool& handled) {
    Value r;
    ok = false;
    handled = true;
    auto kind_of = [&](const std::string& c) { return c == "add_pond" ? "pond" : c == "add_river" ? "river" : c == "add_waterfall" ? "waterfall" : ""; };

    // writes the plan's models into the package and makes the change (one undo step); `replacing` an existing body
    auto commit = [&](Package& pkg, WaterPlan& w, const std::string& replacing, const std::string& label) {
        if (pkg.dir.empty()) return why = "the mod has no package folder", false;
        std::vector<fs::path> created;
        std::error_code ec;
        for (const auto* entry : {&w.main_entry, &w.surface_entry}) {
            const auto& bytes = entry == &w.main_entry ? w.built.main : w.built.surface;
            const fs::path to = fs::u8path(pkg.dir) / fs::u8path(entry->get("source").string());
            if (fs::exists(to, ec)) continue;  // named after its bytes: the same file
            fs::create_directories(to.parent_path(), ec);
            std::ofstream f(to, std::ios::binary);
            f.write(reinterpret_cast<const char*>(bytes.data()), std::streamsize(bytes.size()));
            f.close();
            if (!f) {
                for (const auto& c : created) fs::remove(c, ec);
                return why = "cannot write " + entry->get("source").string() + " into the package", false;
            }
            created.push_back(to);
        }
        const bool kept = change(pkg, label, [&](Value& m, std::string& wy) {
            if (m.get("models").type != Value::Array) m["models"].type = Value::Array;
            if (m.get("actors").type != Value::Array) m["actors"].type = Value::Array;
            if (!replacing.empty()) {
                Value* a = by_id(m["actors"], replacing);
                if (!a) return wy = "no placed actor \"" + replacing + "\"", false;
                const std::string old_main = a->get("model").string(), old_surface = a->get("shoreline").get("model").string();
                *a = w.actor;
                // the old models leave the manifest once nothing uses them (their files stay: undo brings them back)
                auto& list = m["models"].array;
                list.erase(std::remove_if(list.begin(), list.end(), [&](const Value& e) {
                               const std::string id = e.get("id").string();
                               return water_model(e) && (id == old_main || id == old_surface) && !used_by_actor(m, id);
                           }),
                           list.end());
            } else
                m["actors"].array.push_back(w.actor);
            for (const auto* e : {&w.main_entry, &w.surface_entry})
                if (!by_id(m["models"], e->get("id").string())) m["models"].array.push_back(*e);
            return true;
        }, r, why);
        if (!kept) {
            for (const auto& c : created) fs::remove(c, ec);
            return false;
        }
        // the converter prepares both for the game (a thread of its own; the body appears when they are ready)
        if (host_) {
            std::string note, wy;
            Value main = w.main_entry, surface = w.surface_entry;
            main["collision"] = true;
            surface["shoreline"] = w.built.material;
            const bool a = host_->prepare_model(pkg.mod, pkg.dir, main, note, wy), b = a && host_->prepare_model(pkg.mod, pkg.dir, surface, note, wy);
            r["note"] = a && b ? "The water is being prepared for the game; it appears when it is ready." : "The water is in the package; it is prepared when the game starts (" + wy + ")";
        }
        return true;
    };

    if (command == "check_water" || command == "add_pond" || command == "add_river" || command == "add_waterfall") {
        Package* pkg = package(p, why);
        if (!pkg) return r;
        std::string kind = command == "check_water" ? text(p, "kind") : kind_of(command);
        Value q = p;
        // a waterfall at a river's step: its top edge, top and foot from the river
        if (kind == "waterfall" && p.get("river").type == Value::String) {
            water::Params river;
            Value world;
            if (!water_of(pkg->dir, pkg->manifest, p.get("river").text, river, world, why)) return r;
            if (river.kind != "river") return why = "\"" + p.get("river").text + "\" is not a river", r;
            WaterPlan rp;
            if (!plan_water(nullptr, pkg->manifest, "river", world, p.get("river").text, rp, why)) return r;
            const int n = p.get("step").type == Value::Number ? int(p.get("step").number) : 1;
            if (n < 1 || n > int(rp.built.steps.size()))
                return why = rp.built.steps.empty() ? "the river has no step (it steps down where the ground drops)" : "the river has " + std::to_string(rp.built.steps.size()) + " step(s): \"step\" 1 to " + std::to_string(rp.built.steps.size()), r;
            const auto& s = rp.built.steps[size_t(n - 1)];
            q["points"].type = Value::Array;
            q["points"].array.clear();
            for (const XZ e : {s.left, s.right}) {
                Value pt;
                pt["x"] = double(e.x + rp.origin.x), pt["z"] = double(e.z + rp.origin.z);
                q["points"].array.push_back(pt);
            }
            q["top"] = double(s.top + rp.origin_y);
            if (p.get("bottom").type != Value::Number) q["bottom"] = double(s.ground + rp.origin_y);  // the ground at the step's foot
            q["side"] = -1.0;  // the bank points go left to right of the flow: the water falls downstream
            q["stage"] = world.get("stage");
            q["room"] = world.get("room");
            if (p.get("floor").type == Value::Null) q["floor"] = world.get("floor");
        }
        q["mod"] = pkg->mod;
        // check_water on a body being changed (its id): its own models and place don't count against it
        const std::string replacing = command == "check_water" && p.get("id").type == Value::String && by_id(pkg->manifest.get("actors"), p.get("id").text) ? p.get("id").text : "";
        WaterPlan w;
        if (!plan_water(host_, pkg->manifest, kind, q, replacing, w, why)) return r;
        if (command == "check_water") {
            r = plan_result(w);
            ok = true;
            return r;
        }
        if (has_error(w.problems)) {
            why = "not made: " + first_error(w.problems) + (w.problems.size() > 1 ? " (check_water lists every problem)" : "");
            return r;
        }
        std::string id = p.get("id").type == Value::String ? p.get("id").text : free_water_id(pkg->manifest.get("actors"), kind);
        if (!id_ok(id)) return why = "a body of water's id is 1 to 22 lower-case letters, digits, '-', '_' or '.'", r;
        if (by_id(pkg->manifest.get("actors"), id)) return why = "the mod has an actor \"" + id + "\" already", r;
        name_plan(w, id);
        const std::string label = std::string("Add ") + kind + " " + id;
        if (!commit(*pkg, w, "", label)) return r;
        const Value info = plan_result(w);
        for (const auto& [k, v] : info.object)
            if (!r.object.count(k)) r[k] = v;
        r["id"] = id;
        r["actor"] = w.actor;
        ok = true;
        return r;
    }
    if (command == "get_water") {
        Package* pkg = package(p, why);
        if (!pkg) return r;
        water::Params params;
        Value world;
        if (!water_of(pkg->dir, pkg->manifest, text(p, "id"), params, world, why)) return r;
        world.object.erase("ground");
        r = world;
        r["id"] = text(p, "id");
        if (params.kind == "river") {  // its steps (where a waterfall goes) and levels, from the kept ground
            Value again;
            water_of(pkg->dir, pkg->manifest, text(p, "id"), params, again, why);
            WaterPlan rp;
            if (plan_water(nullptr, pkg->manifest, "river", again, text(p, "id"), rp, why)) {
                const Value info = plan_result(rp);
                r["steps"] = info.get("steps");
                r["levels"] = info.get("levels");
            }
        }
        why.clear();
        ok = true;
        return r;
    }
    if (command == "edit_water") {
        Package* pkg = package(p, why);
        if (!pkg) return r;
        const std::string id = text(p, "id");
        water::Params params;
        Value world;
        if (!water_of(pkg->dir, pkg->manifest, id, params, world, why)) return r;
        // the changed parameters over the stored ones (a pond's level, a waterfall's top and bottom are world heights)
        for (const char* key : {"points", "level", "depth", "rim", "foam", "floor", "width", "shallow", "top", "bottom", "side"})
            if (p.get(key).type != Value::Null) world[key] = p.get(key);
        world["mod"] = pkg->mod;
        WaterPlan w;
        if (!plan_water(host_, pkg->manifest, params.kind, world, id, w, why)) return r;
        if (has_error(w.problems)) {
            why = "not changed: " + first_error(w.problems) + (w.problems.size() > 1 ? " (check_water lists every problem)" : "");
            return r;
        }
        name_plan(w, id);
        if (!commit(*pkg, w, id, "Edit water " + id)) return r;
        const Value info = plan_result(w);
        for (const auto& [k, v] : info.object)
            if (!r.object.count(k)) r[k] = v;
        r["id"] = id;
        r["actor"] = w.actor;
        ok = true;
        return r;
    }
    handled = false;
    return r;
}

