std::string text(const Value& p, const char* key) { return p.get(key).string(); }
Value* by_id(Value& list, const std::string& id) {
    if (list.type != Value::Array) return nullptr;
    for (auto& v : list.array)
        if (v.get("id").type == Value::String && v.get("id").text == id) return &v;
    return nullptr;
}
const Value* by_id(const Value& list, const std::string& id) { return by_id(const_cast<Value&>(list), id); }
bool id_ok(const std::string& id) {
    if (id.empty() || id.size() > 22) return false;  // the models add "-m" and eight digits
    for (char c : id)
        if (!((c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') || c == '-' || c == '_' || c == '.')) return false;
    return true;
}
std::string free_water_id(const Value& actors, const std::string& base) {
    if (!by_id(actors, base)) return base;
    for (int n = 2;; n++)
        if (!by_id(actors, base + "-" + std::to_string(n))) return base + "-" + std::to_string(n);
}
// FNV-1a: a short, stable name for generated bytes (not a security measure)
std::string digest8(const std::vector<uint8_t>& b) {
    uint64_t h = 1469598103934665603ULL;
    for (uint8_t c : b) h = (h ^ c) * 1099511628211ULL;
    char s[17];
    std::snprintf(s, sizeof s, "%016llx", static_cast<unsigned long long>(h));
    return std::string(s, 8);
}
bool water_model(const Value& m) { return m.get("source").string().rfind("models/water/", 0) == 0; }
bool used_by_actor(const Value& manifest, const std::string& model) {
    for (const auto& a : manifest.get("actors").array)
        if (a.get("model").string() == model || a.get("collision").get("mesh").string() == model || a.get("shoreline").get("model").string() == model ||
            a.get("distant").get("model").string() == model)
            return true;
    return false;
}
Value problem_value(const water::Problem& p) {
    Value v;
    v["message"] = p.message;
    v["severity"] = p.severity;
    if (!p.field.empty()) v["field"] = p.field;
    for (const auto& [k, x] : p.where.object) v[k] = x;
    return v;
}
bool has_error(const std::vector<water::Problem>& ps) {
    return std::any_of(ps.begin(), ps.end(), [](const water::Problem& p) { return p.severity == "error"; });
}
std::string first_error(const std::vector<water::Problem>& ps) {
    for (const auto& p : ps)
        if (p.severity == "error") return p.message;
    return {};
}
// a world point's y when the parameters give one (picked points have it)
bool point_y(const Value& v, double& y) {
    if (v.type == Value::Object && v.get("y").type == Value::Number && std::isfinite(v.get("y").number)) return y = v.get("y").number, true;
    return false;
}
