// World editor: the water tool's commands (water.h; docs/mod-editor.md "Water"). check_water says what a body of
// water would be and what is wrong with it (nothing changes); add_pond, add_river and add_waterfall make one: two
// generated models in the package (models/water/) and a static world object that uses them, in one undo step;
// edit_water rebuilds one from its stored parameters and the changed ones (one undo step; the old models leave the
// manifest, their files stay for undo); get_water reads them back. The ground comes from the game (Host::grounds),
// and each answer is kept with the body, so a rebuild keeps unmoved points where they were.
