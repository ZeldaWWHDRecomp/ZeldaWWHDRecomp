#!/usr/bin/env python3
"""Extract recompiled originals for the difference tests: the C of each root and of every function it
reaches (calls and fall-through tails) from GEN_DIR, as one translation unit. A hooked root's game code
(f_X_orig) is emitted as f_X, so the tests always run the original. Calls that leave the closure become
stubs into the test runtime: hostrt_test_outside(c, addr) for game functions, hostrt_test_import(c, name)
for imports.

usage: mkclosure.py GEN_DIR OUT.c ADDR...
"""
import glob
import os
import re
import sys

FUNC_RE = re.compile(r"^void f_([0-9A-F]{8})(_orig)?\(Cpu\* __restrict c\) \{$")


def index(gen):
    loc = {}
    for path in sorted(glob.glob(os.path.join(gen, "code_*.c"))):
        lines = open(path).read().split("\n")
        i = 0
        while i < len(lines):
            m = FUNC_RE.match(lines[i])
            if m:
                j = i
                while lines[j] != "}":
                    j += 1
                a = int(m.group(1), 16)
                body = lines[i:j + 1]
                if m.group(2):
                    body[0] = "void f_%08X(Cpu* __restrict c) {" % a
                    loc[a] = body
                elif a not in loc or not any("hook_%08X(c)" % a in l for l in body):
                    if not (len(body) <= 3 and "hook_%08X(c)" % a in "\n".join(body)):
                        loc.setdefault(a, body)
                i = j
            i += 1
    return loc


def drop_dead_tail(body):
    """The recompiler ends every function with a fall-through into the next one; after a return or an
    unconditional branch it is unreachable and is dropped (it would pull the whole program in)."""
    if len(body) >= 3 and "MUSTTAIL return f_" in body[-2]:
        prev = body[-3].split("/*")[0].strip()
        uncond = not prev.startswith(("if ", "if(", "L_"))
        if uncond and ("return;" in prev or "MUSTTAIL return" in prev or prev.startswith("goto ")):
            return body[:-2] + body[-1:]
    return body


# the port-owned blocks (tools/host_runtime/inventory.py): the closure stays inside them; game code the
# runtime calls (operator new/delete, constructors) is a stub the test models
BLOCKS = [(0x0286C590, 0x0286DB50), (0x028EA038, 0x028F626C)]


def owned(a):
    return any(lo <= a < hi for lo, hi in BLOCKS)


def main():
    gen, out = sys.argv[1], sys.argv[2]
    roots = [int(a, 16) for a in sys.argv[3:]]
    # calls and fall-throughs into a hooked function's game code (f_X_orig) are the original here (f_X)
    loc = {a: drop_dead_tail([re.sub(r"\bf_([0-9A-F]{8})_orig\(c\)", r"f_\1(c)", l) for l in b]) for a, b in index(gen).items()}
    todo, have = list(roots), set()
    while todo:
        a = todo.pop()
        if a in have or a not in loc or (a not in roots and not owned(a)):
            continue
        have.add(a)
        for t in re.findall(r"\bf_([0-9A-F]{8})\(c\)", "\n".join(loc[a])):
            todo.append(int(t, 16))
    text = "\n".join("\n".join(loc[a]) for a in sorted(have))
    called = {int(t, 16) for t in re.findall(r"\bf_([0-9A-F]{8})\(c\)", text)}
    imports = sorted(set(re.findall(r"\bimp_(\w+)\(c\)", text)))
    with open(out, "w") as f:
        f.write("/* generated by tools/host_runtime/difftest/mkclosure.py: recompiled originals (game code, keep in build/) */\n")
        f.write('#include "ppc.h"\n#define PPC_GQR_STATIC_FLOAT 0x03\n')
        f.write("void hostrt_test_outside(Cpu* c, uint32_t addr);\nvoid hostrt_test_import(Cpu* c, const char* name);\n")
        for a in sorted(have | called):
            f.write("void f_%08X(Cpu* __restrict c);\n" % a)
        for a in sorted(called - have):
            f.write("void f_%08X(Cpu* __restrict c) { hostrt_test_outside(c, 0x%08Xu); }\n" % (a, a))
        for imp in imports:
            f.write('void imp_%s(Cpu* c) { hostrt_test_import(c, "%s"); }\n' % (imp, imp))
        f.write(text + "\n")
        # indirect calls (function pointers, e.g. printf's output callbacks) reach closure functions
        # through this table (difftest/rt.cpp ppc_dispatch)
        f.write("typedef struct { uint32_t addr; void (*fn)(Cpu*); } ClosureEntry;\n")
        f.write("const ClosureEntry hostrt_test_closure[] = {\n")
        for a in sorted(have):
            f.write("    {0x%08Xu, f_%08X},\n" % (a, a))
        f.write("    {0, 0}};\n")
    print("%d functions, %d outside calls, %d imports -> %s" % (len(have), len(called - have), len(imports), out))


if __name__ == "__main__":
    main()
